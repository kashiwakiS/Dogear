import Foundation

@MainActor
enum ResearchContextSummaryDiagnostics {
    static func run() -> (checks: Int, failures: [String]) {
        var checks = 0
        var failures: [String] = []
        func check(_ condition: @autoclosure () -> Bool, _ message: String) {
            checks += 1
            if !condition() { failures.append(message) }
        }
        var history = ResearchSession(title: "Context fixture")
        for index in 1...7 {
            history.messages.append(ResearchMessage(question: "Q\(index)", answer: "A\(index)", status: .accepted))
        }
        history.messages.append(ResearchMessage(question: "Failed request", status: .failed))
        let selected = ResearchHistorySelection.select(from: history)
        let summary = ResearchContextSummary.capture(session: history, history: selected,
            imageCount: 1, excludedImageCount: 0, isLocalOutline: false)
        check(summary.historyMessageIDs == Array(history.messages[1...6]).map(\.id),
              "The receipt does not identify the actual six complete accepted exchanges.")
        check(summary.availableHistoryRounds == 7 && summary.omittedHistoryRounds == 1 && summary.historyOmission == .roundLimit,
              "Failed requests were counted as usable history or the round-limit omission was hidden.")
        check(summary.historyCharacters == 24, "The receipt counts history that was not included.")
        history.messages.append(ResearchMessage(question: String(repeating: "q", count: 5_000),
            answer: String(repeating: "a", count: 8_000), status: .accepted))
        let oversized = ResearchContextSummary.capture(session: history,
            history: ResearchHistorySelection.select(from: history), imageCount: 0, excludedImageCount: 1, isLocalOutline: false)
        check(oversized.historyMessageIDs.isEmpty && oversized.omittedHistoryRounds == 8
              && oversized.historyOmission == .characterLimit && oversized.historyCharacters == 0,
              "A long latest exchange must disclose that no saved history fit this request.")
        check(oversized.imageCount == 0 && oversized.excludedImageCount == 1,
              "Text-only sending must not claim that excluded image pixels were sent.")
        let local = ResearchContextSummary.capture(session: history, history: selected,
            imageCount: 0, excludedImageCount: 0, isLocalOutline: true)
        check(local.historyMessageIDs.isEmpty && local.historyCharacters == 0 && local.historyOmission == .localOutline,
              "A deterministic local outline must not claim to send saved history.")

        let root = FileManager.default.temporaryDirectory.appendingPathComponent("ResearchContextReceipt-\(UUID().uuidString)")
        defer { try? FileManager.default.removeItem(at: root) }
        do {
            let store = ResearchStore(rootURL: root)
            let source = ResearchSourceSnapshot(fileID: UUID(), displayName: "Frozen.pdf", fingerprint: "v1")
            let id = store.createSession(title: "Frozen", sourceSelection: .init(fileIDs: [source.fileID]))
            guard let requestID = store.beginRequest(sessionID: id, question: "Question", sourceSnapshot: [source],
                contextSummary: summary) else { throw ResearchStoreError.storageUnavailable }
            var changed = store.session(id: id)!
            changed.sourceSelection = ResearchSourceSelection(fileIDs: [UUID()])
            _ = store.updateSession(changed)
            _ = store.finishRequest(sessionID: id, requestID: requestID, answer: "Answer", status: .accepted)
            let restored = ResearchStore(rootURL: root).session(id: id)?.messages.first
            check(restored?.contextSummary == summary && restored?.sourceSnapshot == [source],
                  "Changing current source selection or relaunching rewrote the saved request scope.")
            check(restored?.status == .accepted, "Saving a context receipt broke normal request completion.")

            // Fixed pre-receipt wire record, not generated by the new encoder.
            let oldMessage = Data("""
            {"id":"00000000-0000-0000-0000-000000000001","requestID":"00000000-0000-0000-0000-000000000002",
             "question":"Older question","input":{"text":"","blocks":[]},"sourceSnapshot":[],
             "answer":"Older answer","evidence":[],"status":"accepted","origin":"verifiedAI",
             "operationResults":[],"createdAt":0}
            """.utf8)
            let decoded = try JSONDecoder().decode(ResearchMessage.self, from: oldMessage)
            check(decoded.contextSummary == nil && decoded.answer == "Older answer",
                  "Legacy records must remain readable without inventing a past history selection.")
            let empty = ResearchContextSummary.capture(session: ResearchSession(title: "New"), history: [],
                imageCount: 0, excludedImageCount: 0, isLocalOutline: false)
            check(empty.historyMessageIDs.isEmpty && empty.historyOmission == nil && empty.availableHistoryRounds == 0,
                  "A new session should not display an omission warning.")
        } catch { failures.append("Context receipt persistence: \(error)") }
        return (checks, failures)
    }
}
